const stored = localStorage.getItem('sarahah_lang');
const initial = stored === 'en' || stored === 'ar' ? stored : 'ar';

i18n.use(initReactI18next).init({
  resources: { ar: { t: ar }, en: { t: en } },
  lng: initial,
  fallbackLng: 'ar',
  defaultNS: 't',
  interpolation: { escapeValue: false },
});

function applyDir(lng) {
  const dir = lng === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lng;
  document.documentElement.dir = dir;
  document.title = lng === 'ar' ? 'صراحة الرسائل' : 'Sarahah';
}

applyDir(initial);
i18n.on('languageChanged', (lng) => {
  localStorage.setItem('sarahah_lang', lng);
  applyDir(lng);
});

export default i18n;
